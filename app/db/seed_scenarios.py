def seed_scenarios():
    with SessionLocal() as db:
        created = 0
        skipped = 0

        for scenario_data in SCENARIOS:
            existing = db.scalar(
                select(Scenario).where(
                    Scenario.category == scenario_data["category"],
                    Scenario.subcategory == scenario_data["subcategory"],
                    Scenario.age_min == scenario_data["age_min"],
                    Scenario.age_max == scenario_data["age_max"],
                    Scenario.place == scenario_data["place"],
                )
            )

            if existing is not None:
                skipped += 1
                continue

            scenario = Scenario(**scenario_data)
            db.add(scenario)
            created += 1

        db.commit()

        print(f"Created: {created}")
        print(f"Skipped: {skipped}")


if __name__ == "__main__":
    seed_scenarios()
